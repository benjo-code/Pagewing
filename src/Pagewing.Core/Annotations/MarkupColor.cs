namespace Pagewing.Core.Annotations;

/// <summary>The colours offered for text markup; <see cref="AnnotationPalette"/> maps them to RGB.</summary>
public enum MarkupColor
{
    /// <summary>Yellow, the default of the highlight.</summary>
    Yellow,

    /// <summary>Green.</summary>
    Green,

    /// <summary>Blue, the default of the underline.</summary>
    Blue,

    /// <summary>Pink, the default of the strike-out.</summary>
    Pink,

    /// <summary>Orange.</summary>
    Orange,
}
